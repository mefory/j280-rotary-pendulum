%% j280_params.m — J280 旋转倒立摆物理参数（单一来源）
%% 用法：量好/改好参数 → 运行 lqr_to_rtl.m 生成 rtl/j280_gains.vh
%% 【先验来源】WHEELTEC 论文《基于LQR控制器对旋转倒立摆的稳摆控制》
%%   (2021-12-27) 数值程序——其 dlqr 输出与实机 STM32 出厂增益
%%   k1..k4=[-1.6349,-1.7563,26.8,2.3682] 完全吻合，为当前最可信实机先验。
%%   注意：倒立摆参考/parameter.m（M=滑块、r=同步带轮）是直线摆产品参数，
%%   不可混用；论文自身臂惯量 I 公式误用摆杆质量，此处不采纳。
%% 【TODO(实测)】带 ★ 的参数到手后必须实测替换（尺+秤/STP 质量属性，10 分钟）；
%%   实机辨识后应替换并重新生成增益。
%% ========================================================================
function P = j280_params()

%% ---- 几何（WHEELTEC 论文先验；★ 到手复核）----
P.L_arm   = 0.156;   % 摆臂长：电机轴心 → 摆杆铰点 [m]（论文 r=0.156）
P.L_rod   = 0.135;   % 摆杆等效细杆长（论文杆长 0.135）★
P.lc_rod  = 0.0675;  % 摆杆质心到铰点距离（均质杆=L_rod/2，论文 l=0.0675）★ [m]
P.m_arm   = 0.045;   % 摆臂质量 ★ [kg]（无 WHEELTEC 数据，仍为占位）
P.m_rod   = 0.140;   % 摆杆质量（论文 m=0.140；旧占位 0.060 明显偏轻）★ [kg]

%% ---- 惯量（解析近似：杆/板类零件足够；如要更准做摆动周期辨识）----
P.J_arm = P.m_arm * P.L_arm^2 / 3;          % 摆臂绕电机轴 [kg·m²]（均质细杆）
P.J_rod = P.m_rod * P.L_rod^2 / 12;         % 摆杆绕质心（垂直杆轴）[kg·m²]
% J_rod 始终是质心惯量；不要在这里再加 m*l_c^2（方程中已加一次）。
% L_rod、lc_rod 当前为独立占位，非均匀杆须分别辨识质心与质心惯量。

%% ---- 电机+减速箱（WHEELTEC 论文：12V 铭牌同款；减速比 1:20、13 线霍尔×4 倍频=1040）----
% 论文 R=4.286 与本机堵转推导 12/2.8=4.286 完全一致（同款电机），
% 取论文电枢参数；Kt 不再用堵转点近似（旧 0.231 偏大 ~29%）。
P.Kt  = 0.1797;                    % 电磁转矩系数 [N·m/A]（论文 Km）
P.Ke  = 0.2087;                    % 反电动势系数 [V·s/rad]（论文 Ke）
P.R   = 4.286;                     % 电枢电阻（绕组+驱动导通折算）[Ω]
P.b_vis = P.Kt*P.Ke/P.R + 2e-4;    % 输出轴等效粘滞（反电动势阻尼+齿轮箱）★可辨识
P.b_rod = 1e-4;                  % 摆杆轴承粘滞 [N m s/rad]，与非线性模型一致

%% ---- 其它 ----
P.g   = 9.80665;
P.Vbus  = 12.0;              % 母线电压 [V]
P.duty_full = 10000;         % RTL duty 满幅（±10000 = ±100%）
P.Ts_ctrl = 1e-3;            % 控制周期 [s]
end
