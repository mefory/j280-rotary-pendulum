function kq = lqr_to_rtl(q_theta, use_identified)
% Shared nonlinear-plant Jacobian -> LQR -> signed Q3.13 constants.
% 2026-09-18：Q2.14→Q3.13（scale 16384→8192）。WHEELTEC 先验参数下最小稳定
% 增益 k_alpha≈2.1 duty/cdeg 已超 Q2.14 的 ±2.0 上限，且实机锚点 k_alpha≈3.9
% 要求更大表示域；s16 位宽与全部寄存器/协议不变，仅二进制点左移一位。
%
% 2026-09-23 位置环重设计：θ（摆臂角）权重 0.03 → 3。
%   旧权重下 K3 = 0.0251 duty/cdeg ⇒ 满 30° 误差只产生 75 duty，而执行器死区是
%   350 ⇒ 位置环没有权限，定位实际靠死区补偿抖动"爬"，方向不可控（实机摆臂来回
%   摆、到不了目标；发版门禁 tb_uart_mission 反扭 11.4°）。
%   权重扫描（lqr_scan.m）+ RTL 四方向闭环（tb_closedloop）实测：
%     q_theta=0.03 权限 75  → 末段误差 0.24~0.61°
%     q_theta=1    权限 436 → 末段误差 0.30~0.33°（两个方向都过）
%     q_theta=3    权限 756 → 末段误差 0.34~0.38°（两个方向都过）★采用
%     q_theta=10   权限 1380 → 进 POS 后掉摆（摆臂指令太大干扰摆杆）
%   取 3：权限达死区 2.2 倍（实机死区不确定，需要余量），而摆角峰值 0.48° 距
%   3° 判据仍有 6 倍余量。摆角权重 8 与被控摆杆的稳定整形保持不变。
%
% 2026-09-27 回退到 q_theta=0.03（实机整定定案）：
%   q_theta=3 的增益组 [21858,15748,2064,13166] 上机后稳摆临界不稳定（振荡包络
%   指数增长，1.5~7s 掉摆），位置环权限收益被稳摆失稳完全抵消。agent 接口实机
%   8 轮对照试验（tmp/balance_probe.py）：单通道加 K2/K4/减死区均无效，回退
%   [17751,11613,206,7104] 后 30s 满时长零掉摆、σ=1.71°、含扰动峰 5.9°、零饱和
%   （增长 0.02/s）。POS 位置权限问题今后在 POS 通道内单独解决（如积分/前馈），
%   不再抬稳摆 K3。重生成命令：lqr_to_rtl（无参）。
%
% 2026-09-28 重整定（候选辨识模型）：R5 在真机边缘稳定（存活 0.5~30s 漂移），
% 根因=WHEELTEC 先验模型错配（辨识：J_rod×2.4、b_rod×3.6、motor_gain=0.663）。
% lqr_scan_identified.m 在辨识模型上扫权重：LQR 最优解对权重不敏感，自然收敛到
% k4≈10.4k/k3≈266——整组自洽（此前"2983 上限"来自增益堆叠试验不可比）。
% 用法：lqr_to_rtl(0.03, true) = 辨识模型 + q_theta=0.03。
if nargin < 1, q_theta = 0.03; end
if nargin < 2, use_identified = false; end
if use_identified
    [A,B,P] = j280_linear_model(j280_params_de10_identified());
else
    [A,B,P] = j280_linear_model();
end
Q = diag([q_theta 8 0.05 0.05]); R = 1;
K = lqr(A,B,Q,R);
k = -K([2 4 1 3])*(P.duty_full/P.Vbus).*pi./[18000 1800 18000 1800];
kq = round(k*2^13);
assert(all(abs(kq)<32768),'Q3.13 gain overflow');
Kq = -kq([3 1 4 2])/2^13/(P.duty_full/P.Vbus).*[18000 18000 1800 1800]/pi;
assert(all(real(eig(A-B*Kq))<0),'Unstable quantized feedback');
lqr_lag_check(kq);
dest = fullfile(fileparts(mfilename('fullpath')),'..','rtl','j280_gains.vh');
fid = fopen(dest,'w'); assert(fid>=0); cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'// Generated by matlab/lqr_to_rtl.m. Q=%s, R=%g\n',mat2str(diag(Q)'),R);
fprintf(fid,'// State units: [alpha cdeg, alpha_dot ddeg/s, theta_error cdeg, theta_dot ddeg/s]\n');
fprintf(fid,'// Gains are s16 Q3.13 (scale 8192): duty per state unit = kq/8192\n');
fprintf(fid,'`ifndef J280_GAINS_VH\n`define J280_GAINS_VH\n');
for n=1:4
    if kq(n)<0, value=sprintf('-16''sd%d',-kq(n)); else, value=sprintf('16''sd%d',kq(n)); end
    fprintf(fid,'`define G_K%d (%s)\n',n,value);
end
% POS 专用臂环增益（2026-09-27）：稳摆回退 q_theta=0.03 后 K3 无位置权限，
% 仅在 M_POS 模式把臂环 K3/K4 成对抬到 q_theta=3 时代的实测配对值
% （2064/13166：末段误差 0.34~0.38°）；稳摆模式不受影响。
% 实测教训：只抬 K3 不抬 K4（2600/7104）定位环欠阻尼，late_error 反而恶化到 4.1°。
fprintf(fid,'`define G_K3_POS (16''sd2064) // duty/cdeg*8192=0.252, POS-mode only\n');
fprintf(fid,'`define G_K4_POS (16''sd13166) // duty/(0.1deg/s)*8192=1.607, POS-mode only\n');
fprintf(fid,'`endif\n');
fprintf('Q=%s R=%g, gains Q3.13=%s\n',mat2str(diag(Q)'),R,mat2str(kq));
end
